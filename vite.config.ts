import { defineConfig, type Plugin } from 'vite';
import react from '@vitejs/plugin-react';
import path from 'path';
import fs from 'fs';

/**
 * Dev-only plugin allowing 1-click publishing from Studio Admin directly into
 * the project repository (public/media, public/audio, defaultContent.ts).
 * Only runs in Vite dev mode; completely excluded during production builds.
 */
function publishToProjectPlugin(): Plugin {
  return {
    name: 'publish-to-project-plugin',
    configureServer(server) {
      server.middlewares.use('/api/publish-to-project', async (req, res, next) => {
        if (req.method !== 'POST') return next();

        try {
          const chunks: Buffer[] = [];
          for await (const chunk of req) {
            chunks.push(typeof chunk === 'string' ? Buffer.from(chunk) : chunk);
          }
          const raw = Buffer.concat(chunks).toString('utf8');
          const payload = JSON.parse(raw);
          const { content, media, audio, warnings } = payload;

          // 1. Create Timestamped Backup
          const nowStr = new Date().toISOString().replace(/[:.]/g, '-');
          const backupDir = path.resolve(__dirname, 'backups', `backup_${nowStr}`);
          fs.mkdirSync(backupDir, { recursive: true });

          const defaultContentPath = path.resolve(__dirname, 'src/services/content/defaultContent.ts');
          if (fs.existsSync(defaultContentPath)) {
            fs.copyFileSync(defaultContentPath, path.join(backupDir, 'defaultContent.ts.bak'));
          }

          // 2. Save Media Files
          const mediaDir = path.resolve(__dirname, 'public/media');
          fs.mkdirSync(mediaDir, { recursive: true });
          let mediaCount = 0;

          if (media && typeof media === 'object') {
            for (const item of Object.values(media) as any[]) {
              if (item.dataUrl && item.fileName) {
                const base64Data = item.dataUrl.replace(/^data:[^;]+;base64,/, '');
                const buf = Buffer.from(base64Data, 'base64');
                fs.writeFileSync(path.join(mediaDir, item.fileName), buf);
                mediaCount++;
              }
            }
          }

          // 3. Save Audio Files
          const audioDir = path.resolve(__dirname, 'public/audio');
          fs.mkdirSync(audioDir, { recursive: true });
          let audioCount = 0;

          if (audio && typeof audio === 'object') {
            for (const item of Object.values(audio) as any[]) {
              if (item.dataUrl && item.fileName) {
                const base64Data = item.dataUrl.replace(/^data:[^;]+;base64,/, '');
                const buf = Buffer.from(base64Data, 'base64');
                fs.writeFileSync(path.join(audioDir, item.fileName), buf);
                audioCount++;
              }
            }
          }

          // 4. Update defaultContent.ts
          const updatedContentCode = `/**
 * BUTTERFLY — Canonical Published Content
 * Auto-generated by Studio Admin Publish Workflow.
 * Last Published: ${new Date().toISOString()}
 */

import type { ButterflyContent } from './types';

export const DEFAULT_BUTTERFLY_CONTENT: ButterflyContent = ${JSON.stringify(content, null, 2)};
`;

          fs.writeFileSync(defaultContentPath, updatedContentCode, 'utf8');

          res.statusCode = 200;
          res.setHeader('Content-Type', 'application/json');
          res.end(
            JSON.stringify({
              success: true,
              backupPath: backupDir,
              mediaCount,
              audioCount,
              warnings: warnings || [],
            })
          );
        } catch (err: any) {
          console.error('[publishToProjectPlugin Error]', err);
          res.statusCode = 500;
          res.setHeader('Content-Type', 'application/json');
          res.end(
            JSON.stringify({
              success: false,
              error: err?.message || String(err),
            })
          );
        }
      });
    },
  };
}

// https://vite.dev/config/
export default defineConfig({
  base: '/Butterfly/',
  plugins: [react(), publishToProjectPlugin()],
  resolve: {
    alias: {
      '@': path.resolve(__dirname, './src'),
    },
  },
  server: {
    port: 3000,
    open: false,
  },
  build: {
    target: 'es2022',
    sourcemap: true,
    rollupOptions: {
      output: {
        manualChunks: {
          vendor: ['react', 'react-dom'],
          gsap: ['gsap', '@gsap/react'],
          lenis: ['lenis'],
        },
      },
    },
  },
});

